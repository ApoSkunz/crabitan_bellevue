<?php

declare(strict_types=1);

namespace Tests\Unit\Controller;

use Controller\OrderController;
use Core\Database;
use Core\FeatureFlags;
use Core\Request;
use Model\OrderModel;
use PHPUnit\Framework\TestCase;
use ReflectionMethod;
use ReflectionProperty;
use PHPUnit\Framework\Attributes\AllowMockObjectsWithoutExpectations;

/**
 * Tests unitaires OrderController — gating invoice_auto_generate.
 *
 * Couvre la branche `if (!$autoInvoice) { return; }` ajoutée pour cohérence
 * avec IpnController et OrderAdminController : la facture n'est pas générée
 * automatiquement quand la variable d'environnement est à "false".
 */
#[AllowMockObjectsWithoutExpectations]
class OrderControllerInvoiceGateTest extends TestCase
{
    private \ReflectionProperty $dbInstanceProp;

    protected function setUp(): void
    {
        $dbMock = $this->createStub(Database::class);
        $this->dbInstanceProp = new \ReflectionProperty(Database::class, 'instance');
        $this->dbInstanceProp->setValue(null, $dbMock);

        $_SESSION = [];
        $_POST    = [];
        $_COOKIE  = [];
        $_SERVER['REMOTE_ADDR']     = '127.0.0.1';
        $_SERVER['HTTP_USER_AGENT'] = 'PHPUnit';
        FeatureFlags::flush();
    }

    protected function tearDown(): void
    {
        $this->dbInstanceProp->setValue(null, null);
        FeatureFlags::flush();
        $_SESSION = [];
        $_POST    = [];
        $_COOKIE  = [];
    }

    public function testGenerateAndStoreInvoiceSkipsWhenAutoGenerateDisabled(): void
    {
        FeatureFlags::setCache(['invoice_auto_generate' => ['key' => 'invoice_auto_generate', 'value' => 'false', 'type' => 'bool']]);

        $orders = $this->createMock(OrderModel::class);
        // Si la branche `return` ne court-circuite pas, findByReferenceForInvoice serait appelé.
        $orders->expects($this->never())->method('findByReferenceForInvoice');

        $ctrl = new OrderController(new Request());
        $prop = new ReflectionProperty(OrderController::class, 'orders');
        $prop->setValue($ctrl, $orders);

        $method = new ReflectionMethod(OrderController::class, 'generateAndStoreInvoice');
        $method->invoke($ctrl, 'WEB-CB-XXXX-2026');
    }

    public function testGenerateAndStoreInvoiceProceedsWhenAutoGenerateEnabled(): void
    {
        FeatureFlags::setCache(['invoice_auto_generate' => ['key' => 'invoice_auto_generate', 'value' => 'true', 'type' => 'bool']]);

        $orders = $this->createMock(OrderModel::class);
        // Avec autoInvoice=true, findByReferenceForInvoice doit être appelé.
        // On retourne null pour court-circuiter le flux après le check.
        $orders->expects($this->once())
            ->method('findByReferenceForInvoice')
            ->with('WEB-CB-YYYY-2026')
            ->willReturn(null);

        $ctrl = new OrderController(new Request());
        $prop = new ReflectionProperty(OrderController::class, 'orders');
        $prop->setValue($ctrl, $orders);

        $method = new ReflectionMethod(OrderController::class, 'generateAndStoreInvoice');
        $method->invoke($ctrl, 'WEB-CB-YYYY-2026');
    }

    public function testGenerateAndStoreInvoiceDefaultsToEnabledWhenEnvNotSet(): void
    {
        $orders = $this->createMock(OrderModel::class);
        $orders->expects($this->once())
            ->method('findByReferenceForInvoice')
            ->willReturn(null);

        $ctrl = new OrderController(new Request());
        $prop = new ReflectionProperty(OrderController::class, 'orders');
        $prop->setValue($ctrl, $orders);

        $method = new ReflectionMethod(OrderController::class, 'generateAndStoreInvoice');
        $method->invoke($ctrl, 'WEB-CB-ZZZZ-2026');
    }
}
